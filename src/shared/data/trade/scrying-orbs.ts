/** PoE1 Scrying Orb support.
 *
 *  A Scrying Orb is bound to one map area ("Map Area: Dunes" in the clipboard),
 *  and the trade API gives every area its own entry in the `currency` group of
 *  /api/trade/data/items, expressed as a type + discriminator pair:
 *
 *    { "type": "53116", "text": "Scrying Orb (Dunes)", "disc": "scrying_orb" }
 *
 *  The parenthesised text is display-only and the API rejects it as a base type
 *  ("Unknown item base type"); a search sends
 *  `type: { option: "53116", discriminator: "scrying_orb" }`. The bare
 *  "Scrying Orb" type is also valid and matches every area at once, which is
 *  what the search falls back to when the area chip is switched off.
 *
 *  Probed 2026-07-29 against the live catalog; resynced 2026-11-22 for the 3.30
 *  atlas (100 -> 131 areas). An area missing here silently widens the search to
 *  every area (#652), so resync whenever the atlas rotation changes. Keys are
 *  the area name exactly as the clipboard's "Map Area:" line prints it, which
 *  is the same string the trade text shows in parentheses. Same shape as CHART_ZONES in ./charts.
 */
export const SCRYING_ORB_DISCRIMINATOR = 'scrying_orb'

/** The area a map's Scrying Orb binds to: the map name minus its " Map" suffix
 *  ("Dunes Map" -> "Dunes"). poe.ninja's ScryingOrb overview names its lines
 *  the same way, so this one key reaches both the trade data and ninja. */
export function scryingAreaForMap(mapName: string): string {
  return mapName.replace(/ Map$/, '')
}

