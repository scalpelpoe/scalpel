import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { build } from 'esbuild'

const root = resolve(import.meta.dirname, '..')
const exampleDir = resolve(root, 'plugin-service-examples/native-item-analyzer')
const cargoManifest = resolve(exampleDir, 'native/Cargo.toml')
const executable = resolve(exampleDir, 'native/target/release/native-item-analyzer.exe')
const contractPath = resolve(exampleDir, 'backend.openrpc.json')
const bundlePath = resolve(exampleDir, 'plugin.js')
const templatePath = resolve(exampleDir, 'manifest.template.json')
const distDir = resolve(exampleDir, 'dist')
const check = process.argv.includes('--check')

execFileSync('cargo', ['build', '--release', '--manifest-path', cargoManifest], { stdio: 'inherit' })
const contract = execFileSync(executable, ['--print-contract'], { encoding: 'utf8' }).replaceAll('\r\n', '\n')
const buildResult = await build({
  entryPoints: [resolve(exampleDir, 'src/plugin.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  external: ['@scalpelpoe/plugin-sdk'],
  banner: { js: '// Generated by scripts/build-native-plugin-example.mjs. Do not edit.' },
})
const bundle = buildResult.outputFiles[0].text

if (check) {
  if (readFileSync(contractPath, 'utf8').replaceAll('\r\n', '\n') !== contract) {
    throw new Error(`generated native backend contract is stale: ${contractPath}`)
  }
  if (readFileSync(bundlePath, 'utf8') !== bundle) throw new Error(`generated native plugin bundle is stale: ${bundlePath}`)
} else {
  writeFileSync(contractPath, contract)
  writeFileSync(bundlePath, bundle)
}

const executableBytes = readFileSync(executable)
const sha256 = createHash('sha256').update(executableBytes).digest('hex')
const manifest = JSON.parse(readFileSync(templatePath, 'utf8'))
manifest.nativeBackend.targets['win32-x64'].sha256 = sha256

if (!check) {
  rmSync(distDir, { recursive: true, force: true })
  mkdirSync(distDir, { recursive: true })
  writeFileSync(resolve(distDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  writeFileSync(resolve(distDir, 'plugin.js'), bundle)
  writeFileSync(resolve(distDir, 'backend.openrpc.json'), contract)
  copyFileSync(executable, resolve(distDir, 'native-item-analyzer.exe'))
}
