import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { build } from 'esbuild'
import { generatePluginClientFromFiles } from './generate-plugin-client.mjs'

const root = resolve(import.meta.dirname, '..')
const providerManifest = resolve(root, 'plugin-service-examples/greeting-provider/manifest.json')
const consumerSource = resolve(root, 'plugin-service-examples/greeting-consumer/src/plugin.ts')
const generatedClient = resolve(root, 'plugin-service-examples/greeting-consumer/src/generated/greeting-provider-client.ts')
const consumerBundle = resolve(root, 'plugin-service-examples/greeting-consumer/plugin.js')

export async function buildPluginServiceExamples(check = false) {
  generatePluginClientFromFiles(providerManifest, generatedClient, check)
  const result = await build({
    entryPoints: [consumerSource],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    external: ['@scalpelpoe/plugin-sdk'],
    banner: { js: '// Generated by scripts/build-plugin-service-examples.mjs. Do not edit.' },
  })
  const bundled = result.outputFiles[0].text
  if (check) {
    if (readFileSync(consumerBundle, 'utf8') !== bundled) throw new Error(`generated bundle is stale: ${consumerBundle}`)
  } else {
    writeFileSync(consumerBundle, bundled)
  }
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  buildPluginServiceExamples(process.argv.includes('--check')).catch((error) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
