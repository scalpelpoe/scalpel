import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const PLUGIN_ID = /^[a-z][a-z0-9-]{2,49}$/
const LOCAL_SCHEMA_REF = /^#\/components\/schemas\/([A-Za-z_$][A-Za-z0-9_$]*)$/
const CONTRACT_FILENAME = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,99}\.json$/
const WINDOWS_DEVICE_FILENAME = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i
const RESERVED_METHODS = new Set(['constructor', 'prototype', '__proto__', 'rpc', 'then'])

export function generatePluginClient(manifest, document) {
  if (!manifest?.api) throw new Error('manifest does not declare an API')
  if (!PLUGIN_ID.test(manifest.id ?? '')) throw new Error('manifest.id is not a valid plugin id')
  if (!document || typeof document !== 'object') throw new Error('OpenRPC document must be an object')
  if (typeof document.openrpc !== 'string' || !document.openrpc.startsWith('1.')) {
    throw new Error('OpenRPC document must use specification version 1.x')
  }
  if (document.info?.version !== manifest.api.version) {
    throw new Error(`OpenRPC info.version must equal manifest API version ${manifest.api.version}`)
  }
  if (!Array.isArray(document.methods)) throw new Error('OpenRPC document must contain methods')

  const providerName = pascalCase(manifest.id)
  const clientName = `${providerName}Client`
  const pluginIdConstant = `${constantCase(manifest.id)}_PLUGIN_ID`
  const apiVersionConstant = `${constantCase(manifest.id)}_API_VERSION`
  const schemas = document.components?.schemas ?? {}
  const declaredNames = new Set([
    'PluginApiTransport',
    'PluginClientContext',
    clientName,
    `get${providerName}Client`,
    `require${providerName}Client`,
  ])
  for (const name of Object.keys(schemas)) {
    if (!IDENTIFIER.test(name)) throw new Error(`unsupported schema name: ${name}`)
    if (declaredNames.has(name)) throw new Error(`generated name collision: ${name}`)
    declaredNames.add(name)
  }
  const declarations = Object.entries(schemas).map(([name, schema]) => renderDeclaration(name, schema))
  const seenMethods = new Set()
  for (const method of document.methods) {
    if (!IDENTIFIER.test(method?.name ?? '')) {
      throw new Error(`unsupported OpenRPC method name: ${String(method?.name)}`)
    }
    if (RESERVED_METHODS.has(method.name)) throw new Error(`reserved OpenRPC method name: ${method.name}`)
    if (seenMethods.has(method.name)) throw new Error(`duplicate OpenRPC method: ${method.name}`)
    seenMethods.add(method.name)
  }
  const methods = document.methods.map((method) => renderMethod(method))

  return `// Generated by scripts/generate-plugin-client.mjs. Do not edit.
export interface PluginApiTransport {
  readonly apiVersion: string
  call<TResult = unknown, TParams = unknown>(method: string, params?: TParams): Promise<TResult>
}

export interface PluginClientContext {
  readonly plugins: {
    get(pluginId: string): PluginApiTransport | null
  }
}

export const ${pluginIdConstant} = ${tsString(manifest.id)} as const
export const ${apiVersionConstant} = ${tsString(manifest.api.version)} as const

${declarations.join('\n\n')}${declarations.length ? '\n\n' : ''}export class ${clientName} {
  constructor(private readonly rpc: PluginApiTransport) {}

${methods.map((method) => indent(method, 2)).join('\n\n')}
}

export function get${providerName}Client(ctx: PluginClientContext): ${clientName} | null {
  const rpc = ctx.plugins.get(${pluginIdConstant})
  if (!rpc) return null
  if (rpc.apiVersion !== ${apiVersionConstant}) {
    throw new Error(
      \`Plugin "\${${pluginIdConstant}}" exposes API \${rpc.apiVersion}; expected \${${apiVersionConstant}}\`,
    )
  }
  return new ${clientName}(rpc)
}

export function require${providerName}Client(ctx: PluginClientContext): ${clientName} {
  const client = get${providerName}Client(ctx)
  if (!client) throw new Error(\`Required plugin "\${${pluginIdConstant}}" is unavailable\`)
  return client
}
`

  function renderMethod(method) {
    if (method.paramStructure !== 'by-name') {
      throw new Error(`method ${String(method.name)} must use paramStructure "by-name"`)
    }
    if (!Array.isArray(method.params)) throw new Error(`method ${String(method.name)} must declare params`)
    if (!method.result?.schema) throw new Error(`method ${String(method.name)} must declare a result schema`)
    const paramsName = `${pascalCase(method.name)}Params`
    const parameterNames = new Set()
    const properties = method.params.map((parameter) => {
      if (!parameter || typeof parameter.name !== 'string' || !parameter.schema) {
        throw new Error(`method ${String(method.name)} contains an invalid parameter`)
      }
      if (parameterNames.has(parameter.name)) {
        throw new Error(`method ${String(method.name)} contains duplicate parameter "${parameter.name}"`)
      }
      parameterNames.add(parameter.name)
      const optional = parameter.required === true ? '' : '?'
      return `  ${JSON.stringify(parameter.name)}${optional}: ${schemaType(parameter.schema)}`
    })
    const hasParams = properties.length > 0
    const hasRequiredParams = method.params.some((parameter) => parameter.required === true)
    if (hasParams) {
      if (declaredNames.has(paramsName)) throw new Error(`generated name collision: ${paramsName}`)
      declaredNames.add(paramsName)
      declarations.push(`export interface ${paramsName} {\n${properties.join('\n')}\n}`)
    }
    const resultType = schemaType(method.result.schema)
    const summary = typeof method.summary === 'string' && method.summary ? `/** ${commentText(method.summary)} */\n` : ''
    const signature = hasParams ? `params${hasRequiredParams ? '' : '?'}: ${paramsName}` : ''
    const call = hasParams
      ? `this.rpc.call<${resultType}, ${paramsName}>(${tsString(method.name)}, params)`
      : `this.rpc.call<${resultType}>(${tsString(method.name)})`
    return `${summary}async ${method.name}(${signature}): Promise<${resultType}> {
  return ${call}
}`
  }

  function renderDeclaration(name, schema) {
    if (schema?.type !== 'object') return `export type ${name} = ${schemaType(schema)}`
    const dictionary = dictionaryType(schema)
    if (dictionary) return `export type ${name} = ${dictionary}`
    const required = new Set(schema.required ?? [])
    const properties = Object.entries(schema.properties ?? {}).map(([property, propertySchema]) => {
      const optional = required.has(property) ? '' : '?'
      return `  ${JSON.stringify(property)}${optional}: ${schemaType(propertySchema)}`
    })
    return `export interface ${name} {\n${properties.join('\n')}\n}`
  }

  function schemaType(schema) {
    if (!schema || typeof schema !== 'object') throw new Error('schema must be an object')
    if (typeof schema.$ref === 'string') {
      const match = LOCAL_SCHEMA_REF.exec(schema.$ref)
      if (!match || !(match[1] in schemas)) throw new Error(`unsupported schema reference: ${schema.$ref}`)
      return match[1]
    }
    if (Array.isArray(schema.enum)) {
      if (schema.enum.length === 0) throw new Error('enum schema must not be empty')
      return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
    }
    if (Array.isArray(schema.oneOf)) {
      if (schema.oneOf.length === 0) throw new Error('oneOf schema must not be empty')
      return schema.oneOf.map(schemaType).join(' | ')
    }
    switch (schema.type) {
      case 'string':
        return 'string'
      case 'number':
      case 'integer':
        return 'number'
      case 'boolean':
        return 'boolean'
      case 'null':
        return 'null'
      case 'array':
        if (!schema.items) throw new Error('array schema must declare items')
        return `Array<${schemaType(schema.items)}>`
      case 'object': {
        const dictionary = dictionaryType(schema)
        if (dictionary) return dictionary
        const required = new Set(schema.required ?? [])
        const properties = Object.entries(schema.properties ?? {}).map(([property, propertySchema]) => {
          const optional = required.has(property) ? '' : '?'
          return `${JSON.stringify(property)}${optional}: ${schemaType(propertySchema)}`
        })
        return `{ ${properties.join('; ')} }`
      }
      default:
        throw new Error(`unsupported schema type: ${String(schema.type)}`)
    }
  }

  function dictionaryType(schema) {
    if (schema.additionalProperties === false) return null
    const properties = Object.entries(schema.properties ?? {})
    const required = new Set(schema.required ?? [])
    const propertyType = `{ ${properties
      .map(([property, propertySchema]) => {
        const optional = required.has(property) ? '' : '?'
        return `${JSON.stringify(property)}${optional}: ${schemaType(propertySchema)}`
      })
      .join('; ')} }`
    const values =
      schema.additionalProperties === undefined || schema.additionalProperties === true
        ? 'unknown'
        : typeof schema.additionalProperties === 'object'
          ? schemaType(schema.additionalProperties)
          : null
    if (values === null) throw new Error('invalid additionalProperties schema')
    if (properties.length === 0) return `Record<string, ${values}>`
    if (values !== 'unknown') {
      throw new Error('objects with properties and typed additionalProperties are unsupported')
    }
    return `${propertyType} & Record<string, ${values}>`
  }
}

export function generatePluginClientFromFiles(manifestPath, outPath, check = false) {
  const resolvedManifest = resolve(manifestPath)
  const manifest = JSON.parse(readFileSync(resolvedManifest, 'utf8'))
  if (!manifest.api?.contract) throw new Error('manifest.api.contract is required')
  if (!isSafeContractFilename(manifest.api.contract)) throw new Error('manifest.api.contract is not a safe filename')
  const contractPath = resolve(dirname(resolvedManifest), manifest.api.contract)
  const document = JSON.parse(readFileSync(contractPath, 'utf8'))
  const generated = generatePluginClient(manifest, document)
  const resolvedOut = resolve(outPath)

  if (check) {
    if (!existsSync(resolvedOut) || readFileSync(resolvedOut, 'utf8') !== generated) {
      throw new Error(`generated client is stale: ${resolvedOut}`)
    }
    return generated
  }

  mkdirSync(dirname(resolvedOut), { recursive: true })
  writeFileSync(resolvedOut, generated)
  return generated
}

function pascalCase(value) {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('')
}

function constantCase(value) {
  return value.replace(/[^A-Za-z0-9]+/g, '_').toUpperCase()
}

function tsString(value) {
  return `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

function commentText(value) {
  return String(value).replaceAll('*/', '* /').replaceAll(/\s+/g, ' ').trim()
}

function isSafeContractFilename(value) {
  return (
    CONTRACT_FILENAME.test(value) &&
    value.toLowerCase() !== 'manifest.json' &&
    !WINDOWS_DEVICE_FILENAME.test(value)
  )
}

function indent(value, spaces) {
  const prefix = ' '.repeat(spaces)
  return value
    .split('\n')
    .map((line) => `${prefix}${line}`)
    .join('\n')
}

function argument(name) {
  const index = process.argv.indexOf(name)
  return index === -1 ? null : process.argv[index + 1]
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const manifestPath = argument('--manifest')
  const outPath = argument('--out')
  if (!manifestPath || !outPath) {
    console.error('Usage: node scripts/generate-plugin-client.mjs --manifest <manifest.json> --out <client.ts> [--check]')
    process.exitCode = 1
  } else {
    try {
      generatePluginClientFromFiles(manifestPath, outPath, process.argv.includes('--check'))
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error))
      process.exitCode = 1
    }
  }
}
