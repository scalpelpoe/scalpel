const itemModsTarget = {
  game: 'poe1',
  from: 'item/Generated.Item.ENGLISH.json',
  to: 'item/GeneratedItemMods.ts',
  render: (json, header, ctx) => {
    const keyed = {}
    for (const entry of json) if (ctx.itemClasses.has(entry.basetype)) keyed[entry.basetype] = entry
    const body = Object.entries(keyed).map(([k, v]) => `  ${str(k)}: ${JSON.stringify(v)},`)
    return [
      header,
      ITEM_MODS_TYPES,
      'export const itemRegex: { [key: string]: ItemRegex } = {',
      ...body,
      '}',
      '',
    ].join('\n')
  },
}

/** Verbatim port of poe2.re's parseAffixToken (src/lib/parseAffixToken.ts). */
function parseAffixToken(token) {
  const ranges = []
  const values = []
  const lines = token.rawText.split('\n')
  const processed = lines.map((line) => {
    let out = line
    out = out.replace(/\(([+-]?\d+)-([+-]?\d+)\)/g, (_m, a, b) => {
      ranges.push([Number(a), Number(b)])
      return '##'
    })
    out = out.replace(/(?<![A-Za-z0-9])\+?(\d+)(?![A-Za-z0-9])/g, (_m, n) => {
      values.push(Number(n))
      return '#'
    })
    out = out.replace(/\[([^\]]+)\]/g, '$1')
    return out
  })
  return {
    id: token.id,
    name: processed.join('|'),
    regex: token.regex,
    values,
    ranges,
    prefix: !!token.options.prefix,
    tags: token.options.tags ?? [],
  }
}

function affixTokenTarget({ dir, typeName, constName, from }) {
  const to = `${dir}/${typeName.replace('Regex', '')}.Gen.ts`
  return {
    game: 'poe2',
    from,
    to,
    render: (json, header) => {
      const pinned = existingIds(to)
      const mods = pinIds(
        json.tokens.map(parseAffixToken).sort((a, b) => a.name.localeCompare(b.name)),
        pinned,
        (m) => collapse(m.name),
        (m) => m.id,
      )
      return `${header}

export interface ${typeName} {
  id: number
  name: string
  regex: string
  values: number[]
  ranges: number[][]
  prefix: boolean
  tags: string[]
}

export const ${constName}: ${typeName}[] = ${JSON.stringify(mods, null, 2)}
`
    },
  }
}

/** Relic mods upstream reworded without changing the mod: new text -> previously
 *  committed text, so the old id (and every preset holding it) carries over. */
const RELIC_RENAMES = {
  '#% increased Armour, Evasion and Energy Shield': '#% increased Defences',
  '+# metres to Dodge Roll distance': '+(#.#-#.#) metres to Dodge Roll distance',
}

const relicTarget = {
  game: 'poe2',
  from: 'relic/Generated.Relic.ENGLISH.json',
  to: 'relics/Relic.Gen.ts',
  render: (json, header) => {
    const pinned = existingIds('relics/Relic.Gen.ts')
    const mods = pinIds(
      json
        .map((m) => ({
          id: m.id,
          name: m.name,
          regex: m.regex,
          values: m.values ?? [],
          ranges: m.ranges ?? [],
          affix: m.affix,
        }))
        .sort((a, b) => a.name.localeCompare(b.name)),
      pinned,
      (m) => (pinned.has(collapse(m.name)) ? collapse(m.name) : (RELIC_RENAMES[m.name] ?? collapse(m.name))),
      (m) => hashId(`${m.name}|${m.affix}`),
    )
    return `${header}
// Ids are pinned to the previously committed id per mod text (presets store them).

export interface RelicRegex {
  id: number
  name: string
  regex: string
  values: number[]
  ranges: number[][]
  affix: 'PREFIX' | 'SUFFIX'
}

export const relicRegex: RelicRegex[] = ${JSON.stringify(mods, null, 2)}
`
  },
}

const TARGETS = [
  ...LANGUAGES.map(mapModsTarget),
  gemsTarget,
  beastTarget,
  itemBasesTarget,
  itemModsTarget,
  affixTokenTarget({
    dir: 'waystones',
    typeName: 'WaystoneRegex',
    constName: 'waystoneRegex',
    from: 'waystone/Generated.Waystone.ENGLISH.min.json',
  }),
  affixTokenTarget({
    dir: 'tablets',
    typeName: 'TabletRegex',
    constName: 'tabletRegex',
    from: 'tablet/Generated.Tablet.ENGLISH.min.json',
  }),
  relicTarget,
]

// ---------------------------------------------------------------------- main

async function sync() {
  console.log('[sync-regex] Resolving current patches from data.poe.re...')
  let meta = {}
  if (!FORCE && fs.existsSync(META_FILE)) {
    try {
      meta = JSON.parse(fs.readFileSync(META_FILE, 'utf-8'))
    } catch {}
  }
  const prevFiles = meta.source === ORIGIN ? (meta.files ?? {}) : {}

  const current = JSON.parse((await get(`${ORIGIN}/current.json`)).toString('utf-8')).current
  const sums = {}
  for (const game of ['poe1', 'poe2']) {
    const { patch } = current[game]
    sums[game] = parseSums((await get(`${ORIGIN}/generated/${game}/${patch}/SHA256SUMS`)).toString('utf-8'))
  }

  // Item bases + mods share a class filter read from the committed bases file,
  // so capture it before either is rewritten.
  const ctx = { itemClasses: shippedItemClasses() }
  const files = {}
  let updated = 0
  let failed = 0

  for (const target of TARGETS) {
    const { patch } = current[target.game]
    const key = `${target.game}/${target.from}`
    const sha = sums[target.game][target.from]
    if (!sha) {
      console.warn(`[sync-regex]   ${key} is not published for ${patch}; keeping committed ${target.to}`)
      if (prevFiles[key]) files[key] = prevFiles[key]
      failed++
      continue
    }
    files[key] = { patch, sha256: sha }
    if (prevFiles[key]?.sha256 === sha && readExisting(target.to) !== null) continue

    try {
      const buf = await get(`${ORIGIN}/generated/${target.game}/${patch}/${target.from}`)
      const actual = crypto.createHash('sha256').update(buf).digest('hex')
      if (actual !== sha) throw new Error(`sha256 mismatch (got ${actual.slice(0, 12)}, want ${sha.slice(0, 12)})`)
      const content = target.render(JSON.parse(buf.toString('utf-8')), attribution(target.game, patch), ctx)
      if (readExisting(target.to) !== content) {
        const out = path.join(OUTPUT_DIR, target.to)
        fs.mkdirSync(path.dirname(out), { recursive: true })
        fs.writeFileSync(out, content)
        updated++
        console.log(`[sync-regex]   Updated ${target.to}`)
      }
    } catch (err) {
      console.warn(`[sync-regex]   Failed ${key}: ${err.message}`)
      if (prevFiles[key]) files[key] = prevFiles[key]
      else delete files[key]
      failed++
    }
  }

  const next = {
    source: ORIGIN,
    poe1: { patch: current.poe1.patch, commit: current.poe1.commit },
    poe2: { patch: current.poe2.patch, commit: current.poe2.commit },
    files,
  }
  // Only touch the tracked meta file when something actually changed.
  const { timestamp: _ts, ...prevComparable } = meta
  if (updated > 0 || JSON.stringify(prevComparable) !== JSON.stringify(next)) {
    fs.writeFileSync(META_FILE, `${JSON.stringify({ ...next, timestamp: new Date().toISOString() }, null, 2)}\n`)
  }
  const source = 'mapmods/Generated.Map.ENGLISH.json'
  const english = files[`poe1/${source}`]
  if (english) {
    await syncMapRewards({
      tokenUrl: `${ORIGIN}/generated/poe1/${english.patch}/${source}`,
      sha256: english.sha256,
      force: FORCE,
      userAgent: USER_AGENT,
      get,
    })
  }
  console.log(
    `[sync-regex] poe1 ${current.poe1.patch}, poe2 ${current.poe2.patch}: ${updated} file(s) updated${failed ? `, ${failed} failed` : ''}.`,
  )
}

sync().catch((err) => {
  console.error('[sync-regex] Sync failed:', err.message)
  process.exit(1)
})
