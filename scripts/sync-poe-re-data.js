#!/usr/bin/env node
/**
 * Sync regex data from poe.re's published dataset (https://data.poe.re).
 * Used with permission, with attribution. All credit to veiset and contributors.
 *
 * Resolves the current patch per game from data.poe.re/current.json, reads that
 * patch's SHA256SUMS, downloads only the files whose hash changed since the last
 * sync (files under a patch are NOT immutable: the generator can republish them),
 * verifies each download against its hash, and renders it into the TS shape the
 * app imports from src/shared/data/regex/vendor/.
 *
 * Run manually: npm run sync-regex  (add --force to re-render everything)
 *
 * Not covered: flaskmods/GeneratedFlaskMods.ts. data.poe.re publishes no flask
 * data, so that file is frozen at its last poe-vendor-string sync.
 *
 * Selection ids are persisted in user presets, so for PoE2 waystone/tablet/relic
 * mods the id already committed for a given mod text is kept; only mods new to
 * the dataset take a fresh id. Never let a resync renumber existing mods.
 */

const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')
const { syncMapRewards } = require('./build-map-rewards')

const ORIGIN = 'https://data.poe.re'
const OUTPUT_DIR = path.join(__dirname, '..', 'src', 'shared', 'data', 'regex', 'vendor')
const META_FILE = path.join(OUTPUT_DIR, '.sync-meta.json')
const FORCE = process.argv.includes('--force')
// data.poe.re asks every client to identify as `<name>/<version> (<url>)`
// (poe.re AGENTS.md, "Generated data").
const USER_AGENT = `scalpel-sync-regex/${require('../package.json').version} (https://github.com/scalpelpoe/scalpel)`

const LANGUAGES = [
  'CHINESE',
  'ENGLISH',
  'FRENCH',
  'GERMAN',
  'JAPANESE',
  'KOREAN',
  'PORTUGUESE',
  'RUSSIAN',
  'SPANISH',
  'THAI',
]

const str = (s) => JSON.stringify(s)
const collapse = (s) => s.replace(/##/g, '#')

function attribution(game, patch) {
  return [
    `// Data sourced from poe.re (${ORIGIN}/generated/${game}/${patch})`,
    '// Used with permission. All credit to veiset and contributors.',
    '// Generated by scripts/sync-poe-re-data.js -- do not edit by hand.',
  ].join('\n')
}

async function get(url) {
  const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT } })
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`)
  return Buffer.from(await res.arrayBuffer())
}

function parseSums(text) {
  const sums = {}
  for (const line of text.split('\n')) {
    const m = line.trim().match(/^([0-9a-f]{64})\s+\*?(.+)$/)
    if (m) sums[m[2]] = m[1]
  }
  return sums
}

function readExisting(rel) {
  const p = path.join(OUTPUT_DIR, rel)
  return fs.existsSync(p) ? fs.readFileSync(p, 'utf-8') : null
}

/** Pull `"id": N` keyed by mod text out of a committed *.Gen.ts so ids survive a resync.
 *  Keyed on text alone: upstream does reclassify affix type (Vaal Beacon tablet mods
 *  moved prefix -> suffix), and that must not orphan saved presets. */
function existingIds(rel) {
  const src = readExisting(rel)
  if (!src) return new Map()
  const start = src.indexOf('= [')
  if (start < 0) return new Map()
  const arr = JSON.parse(src.slice(start + 2))
  return new Map(arr.map((m) => [collapse(m.name), m.id]))
}

/** Keep the committed id for a known mod; dedupe against every id already taken. */
function pinIds(mods, pinned, keyOf, freshId) {
  const used = new Set()
  for (const m of mods) {
    const prev = pinned.get(keyOf(m))
    if (prev !== undefined && !used.has(prev)) m.id = prev
    else {
      let id = freshId(m)
      while (used.has(id)) id = (id + 1) | 0
      m.id = id
    }
    used.add(m.id)
  }
  return mods
}

/** FNV-1a 32-bit hash -> unsigned int. Fallback id for mods upstream publishes without one. */
function hashId(s) {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return h >>> 0
}

// ---------------------------------------------------------------- renderers

function renderTokenRegex({ header, importLine, exportLine, json, renderOptions }) {
  const tokens = json.tokens.map(
    (t) =>
      `    {id: ${t.id}, regex: ${str(t.regex)}, rawText: ${str(t.rawText)}, generalizedText: ${str(t.generalizedText)}, options: ${renderOptions(t.options)}},`,
  )
  const optimizations = Object.entries(json.optimizationTable).map(
    ([key, v]) =>
      `    ${str(key)}: {ids: [${v.ids.join(', ')}], regex: ${str(v.regex)}, weight: ${v.weight}, count: ${v.count}},`,
  )
  return [
    header,
    '// @formatter:off',
    importLine,
    '',
    `${exportLine} = {`,
    '  tokens: [',
    ...tokens,
    '  ],',
    '  optimizationTable: {',
    ...optimizations,
    '  },',
    '}',
    '',
  ].join('\n')
}

function mapModsTarget(language) {
  return {
    game: 'poe1',
    from: `mapmods/Generated.Map.${language}.json`,
    to: `mapmods/Generated.MapModsV3.${language}.ts`,
    render: (json, header) =>
      renderTokenRegex({
        header,
        importLine: 'import {Regex, MapModsTokenOption} from "./GeneratedTypes";',
        exportLine: `export const regexMapMods${language}: Regex<MapModsTokenOption>`,
        json,
        renderOptions: (o) => {
          // Locale files keep category names. build-map-rewards emits the numeric table once for all locales.
          const rewards = (o.rewards ?? []).map((r) => (typeof r === 'string' ? r : r.type))
          const tail = rewards.length ? `, rewards: [${rewards.map(str).join(', ')}]` : ''
          return `{scary: ${o.scary}, nm: ${o.nm}, prefix: ${o.prefix}${tail}}`
        },
      }),
  }
}

